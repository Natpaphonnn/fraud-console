"""Build self-contained Kaggle versions of the notebooks.

Kaggle cannot see this repo, so each generated notebook starts with a bootstrap
cell that writes the `fraud_e2e` package and `configs/cost.yaml` into
/kaggle/working and recreates the locked split (deterministic; guarded by
tests/test_splits.py). The rest of the notebook is identical to the repo version.

Output: kaggle/<name>.ipynb (not executed; Kaggle runs it). Upload is manual.

    uv run python scripts/build_kaggle.py
"""

from __future__ import annotations

import base64
from pathlib import Path

import jupytext
import nbformat

REPO = Path(__file__).resolve().parents[1]
SRC = REPO / "src" / "fraud_e2e"
NB_SRC = REPO / "notebooks" / "py"
OUT = REPO / "kaggle"
DATASET_URL = "https://www.kaggle.com/datasets/uditjain13/credit-card-fraud-detection-2026"


# Artifacts each notebook reads from earlier notebooks (Kaggle runs notebooks separately).
_CV = "reports/cv"
REPO_ONLY = {"web.py", "export.py"}  # website only; not needed on Kaggle
NEEDS: dict[str, list[str]] = {
    "04_modeling": [f"{_CV}/logreg.{x}" for x in ("folds.csv", "spec.json", "oof.csv.gz")]
    + [f"{_CV}/logreg_balanced.{x}" for x in ("folds.csv", "spec.json")],
    "05_threshold_and_cost": [f"{_CV}/final.{x}" for x in ("folds.csv", "spec.json", "oof.csv.gz")]
    + ["reports/p2_modeling.json"],
    "06_explainability": [f"{_CV}/final.{x}" for x in ("folds.csv", "spec.json", "oof.csv.gz")]
    + ["reports/p2_modeling.json", "reports/p2_threshold_web.json"],
    "08_fairness": [f"{_CV}/final.{x}" for x in ("folds.csv", "spec.json", "oof.csv.gz")]
    + ["reports/p2_threshold.json", "reports/p2_shap.json"],
    "09_interactions": [f"{_CV}/final.{x}" for x in ("folds.csv", "spec.json")],
}


def bootstrap_source(stem: str) -> str:
    files = {
        f"src/fraud_e2e/{p.name}": p.read_text()
        for p in sorted(SRC.glob("*.py"))
        if p.name not in REPO_ONLY
    }
    files["configs/cost.yaml"] = (REPO / "configs" / "cost.yaml").read_text()
    binary = {}
    for rel in NEEDS.get(stem, []):
        path = REPO / rel
        if rel.endswith(".gz"):
            binary[rel] = base64.b64encode(path.read_bytes()).decode()
        else:
            files[rel] = path.read_text()
    lines = [
        "# Bootstrap: write the project package (and upstream artifacts) into the working",
        "# directory. Auto-generated by scripts/build_kaggle.py.",
        "import base64, os, sys",
        "from pathlib import Path",
        'WORK = Path(os.environ.get("KAGGLE_WORKING_DIR", "/kaggle/working"))',
        f"FILES = {files!r}",
        f"BINARY = {binary!r}",
        "for rel, text in FILES.items():",
        "    p = WORK / rel",
        "    p.parent.mkdir(parents=True, exist_ok=True)",
        "    p.write_text(text)",
        "for rel, b64 in BINARY.items():",
        "    p = WORK / rel",
        "    p.parent.mkdir(parents=True, exist_ok=True)",
        "    p.write_bytes(base64.b64decode(b64))",
        'sys.path.insert(0, str(WORK / "src"))',
        "from fraud_e2e import config as C",
        "from fraud_e2e.data import load_raw",
        "from fraud_e2e.splits import make_splits, save_splits",
        "if not C.SPLITS_CSV.exists():",
        "    save_splits(make_splits(load_raw()))",
        'print("fraud_e2e ready; data:", C.RAW_CSV)',
    ]
    return "\n".join(lines)


def build(py_path: Path) -> Path:
    nb = jupytext.read(py_path)
    header = nbformat.v4.new_markdown_cell(
        "> **Kaggle edition.** Generated from the project repository by "
        "`scripts/build_kaggle.py`. Attach the dataset "
        f"[Credit Card Fraud Detection 2026]({DATASET_URL}) (CC0) before running. "
        "The first code cell installs the project's helper package into `/kaggle/working` "
        "(plus any results this notebook reads from earlier notebooks). Library versions on "
        "Kaggle may differ from the repo's `uv.lock`, so the last digits can differ."
    )
    boot = nbformat.v4.new_code_cell(bootstrap_source(py_path.stem))
    nb.cells = [nb.cells[0], header, boot, *nb.cells[1:]]
    nb.metadata["kernelspec"] = {
        "display_name": "Python 3",
        "language": "python",
        "name": "python3",
    }
    OUT.mkdir(exist_ok=True)
    out = OUT / f"{py_path.stem}.ipynb"
    nbformat.write(nb, out)
    return out


STORY = REPO / "notebooks" / "story" / "fraud_story.py.tmpl"


def story_text(ctx: dict[str, str]) -> str:
    from fraud_e2e.summary import render

    return render(STORY.read_text(), ctx)


def build_story() -> Path:
    """kaggle/fraud_story.ipynb: one self-contained 10-minute notebook (no project package needed).

    Live results are computed in the notebook; quoted project results and settings are injected here
    from reports/ and the project code, so no number is typed by hand.
    """
    import json

    from fraud_e2e import config as C
    from fraud_e2e.features import LOG_COLS
    from fraud_e2e.models import DEFAULTS, SMOTE_K, SMOTE_RATIO
    from fraud_e2e.summary import build_context, load_links

    links = load_links()
    reports = REPO / "reports"
    modeling = json.loads((reports / "p2_modeling.json").read_text())
    thr = json.loads((reports / "p2_threshold.json").read_text())["threshold"]
    ctx = build_context() | {
        "cat_cols": repr(C.CATEGORICAL_COLS),
        "bool_cols": repr(C.BOOLEAN_COLS),
        "num_cols": repr(C.NUMERIC_COLS),
        "log_cols": repr(LOG_COLS),
        "lgbm_default": repr(DEFAULTS["lgbm"]),
        "lgbm_tuned": repr(modeling["tuning"]["best_params"]),
        "smote_ratio": repr(SMOTE_RATIO),
        "smote_k": repr(SMOTE_K),
        "threshold_raw": repr(thr),
        "url_github": links["github"] or "(GitHub link: see configs/links.yaml)",
        "url_website": links["website"] or "(website link: see configs/links.yaml)",
    }
    nb = jupytext.reads(story_text(ctx), fmt="py:percent")
    nb.metadata["kernelspec"] = {
        "display_name": "Python 3",
        "language": "python",
        "name": "python3",
    }
    OUT.mkdir(exist_ok=True)
    out = OUT / "fraud_story.ipynb"
    nbformat.write(nb, out)
    return out


if __name__ == "__main__":
    for py in sorted(NB_SRC.glob("*.py")):
        if py.stem == "00_summary":  # reads every other notebook's results; repo-only
            continue
        print("built", build(py).relative_to(REPO))
    print("built", build_story().relative_to(REPO))
