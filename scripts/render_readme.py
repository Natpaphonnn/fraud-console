"""Render the README results block from committed artifacts (rule: no hand-typed numbers).

uv run python scripts/render_readme.py          # rewrite README.md in place
uv run python scripts/render_readme.py --check  # exit 1 if README is out of date
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
README = REPO / "README.md"
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def j(name: str) -> dict:
    return json.loads((REPO / "reports" / f"{name}.json").read_text())


def ci(d: dict, pct: bool = False, nd: int = 3) -> str:
    f = (lambda x: f"{100 * x:.1f}%") if pct else (lambda x: f"{x:.{nd}f}")
    return f"{f(d['value'])} [{f(d['ci_low'])}, {f(d['ci_high'])}]"


def render() -> str:
    data = j("p1_data_understanding")
    allrow = next(r for r in data["class_balance"] if r["subset"] == "all")
    mod, thr = j("p2_modeling"), j("p2_threshold")
    hold, post, tt = j("p2_holdout"), j("p2_holdout_posthoc"), j("p2_three_tier")
    web = j("p2_threshold_web")
    fin = mod["final_pipeline"]
    m = hold["metrics"]
    d4 = next(d for d in mod["decisions"] if d["step"].startswith("4."))
    abl = mod["ablation_ai_flag"]
    lines = [
        START,
        "<!-- generated by scripts/render_readme.py from reports/*.json; do not edit by hand -->",
        "",
        f"Data: {allrow['n']:,} transactions, {allrow['n_fraud']} fraud "
        f"({allrow['fraud_rate_%']:.3f}%). Final model: **{fin['spec']['model']}** "
        f"(spec `{fin['spec_id']}`).",
        "",
        "| Metric | CV on dev (15 folds, mean [95% CI]) | Holdout, scored once (stratified bootstrap 95% CI) |",
        "|---|---|---|",
        f"| PR-AUC (primary) | {fin['pr_auc']['mean']:.3f} [{fin['pr_auc']['ci_low']:.3f}, "
        f"{fin['pr_auc']['ci_high']:.3f}] | {ci(m['pr_auc'])} |",
        f"| ROC-AUC | {fin['roc_auc']['mean']:.3f} [{fin['roc_auc']['ci_low']:.3f}, "
        f"{fin['roc_auc']['ci_high']:.3f}] | {ci(m['roc_auc'])} |",
        f"| No-skill PR-AUC (= fraud rate) | {web['n_fraud'] / web['n_rows']:.4f} "
        f"| {m['base_rate']['value']:.4f} |",
        f"| Recall at step-up threshold {thr['threshold']:.4f} | {100 * thr['recall']:.1f}% | "
        f"{ci(m['recall'], pct=True)} |",
        f"| Precision at that threshold | {100 * thr['precision']:.1f}% | {ci(m['precision'], pct=True)} |",
        f"| Share of transactions stepped up | {100 * thr['alert_rate']:.2f}% | "
        f"{ci(m['alert_rate'], pct=True)} |",
        f"| Cost saving vs stepping up nobody* | {100 * thr['saving_vs_flag_nothing']:.1f}% | "
        f"{ci(post['two_tier_saving_vs_nothing'], pct=True)} (post-hoc, descriptive) |",
        "",
        "\\* **Illustrative assumed costs, not bank data** (`configs/cost.yaml`). "
        "The threshold was chosen on dev out-of-fold predictions only.",
        "",
        "**What the pre-registered comparisons found**",
        "",
        f"- Logistic regression beat the best gradient-boosting pipeline (`{d4['b']}`): PR-AUC "
        f"difference {d4['mean_diff_b_minus_a']:+.3f} [{d4['ci_low']:+.3f}, {d4['ci_high']:+.3f}] "
        "(boosting minus logistic, corrected resampled t-test).",
        "- Imbalance handling on LightGBM, each vs the current choice (PR-AUC difference [95% CI]): "
        + "; ".join(
            f"{d['b'].split('_', 1)[1]} {d['mean_diff_b_minus_a']:+.3f} "
            f"[{d['ci_low']:+.3f}, {d['ci_high']:+.3f}] → kept `{d['chosen']}`"
            for d in mod["decisions"]
            if d["step"].startswith("2.")
        )
        + ". Notebook 04 shows why SMOTENC hurts here.",
        f"- `is_ai_generated_scam_attempt` adds PR-AUC {abl['mean_diff_b_minus_a']:+.3f} "
        f"[{abl['ci_low']:+.3f}, {abl['ci_high']:+.3f}].",
        f"- Three-tier policy (decline above {tt['t_decline']:.3f}): on the holdout, three-tier minus "
        "two-tier cost under the same assumptions = "
        f"{post['three_tier_model__three_minus_two_per_1000']['value']:+.0f} USD per 1,000 "
        f"[{post['three_tier_model__three_minus_two_per_1000']['ci_low']:+.0f}, "
        f"{post['three_tier_model__three_minus_two_per_1000']['ci_high']:+.0f}] "
        "(post-hoc, descriptive).",
        END,
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    text = README.read_text()
    i, k = text.index(START), text.index(END) + len(END)
    new = text[:i] + render() + text[k:]
    if "--check" in sys.argv:
        sys.exit(0 if new == text else 1)
    README.write_text(new)
    print("README results block updated")
